#include<stdio.h>

int main()
{
    //bitwise operator
int a=12,b=5;
printf("bitwise operators\n");
 printf("a&b=%d\n",a&b);
 printf("a|b=%d\n",a|b);
 printf("a^b=%d\n",a^b);
 printf("a<<2=%d\n",a<< 2);
 printf("a>>2=%d\n",a>>2);


//assignment operator
printf("assignment operator\n ");
int c=10,d=20;
printf("c+=5 %d\n",c);
printf("d+=5 %d\n",d);
printf("c*=5 %d\n",c);
printf("d%%=5 %d\n",d);

 return 0;


}
